/** Bake CC0 Mesh2Motion animation landmarks without shipping its display mesh.
 * Run: node --import tsx scripts/build-motion.ts <directory containing source GLBs>
 * Source URLs, licenses and pinned hashes: public/assets/animations/mesh2motion/.
 */
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {resolve} from 'node:path';
import * as THREE from 'three';
import {GLTFLoader} from 'three/addons/loaders/GLTFLoader.js';

const folder=resolve(process.argv[2]??'artifacts/mesh2motion-research');
const sources=[
 {file:'human-base-animations.glb',sha256:'406eb0a8dc4ab366e623b79b6e3005a4951392e1bda78ae39c1099d31147733c',clips:['Idle_A','Walk','Jog','Sprint','Crouch_Idle','Crouch_Walk','Jump_Start','Jump_air','Jump_Land','Pistol_Reload']},
 {file:'human-addon-animations.glb',sha256:'a0d64d555e0d492026b72d58bf8e16c5e86779295f9093e376dcc001915c2c95',clips:['Idle_Subtle','Walk_Backwards','Strafe_left','Strafe_right','Crawl']},
];
const joints={pelvis:'pelvis',chest:'neck_01',head:'head',leftShoulder:'upperarm_l',leftElbow:'lowerarm_l',leftWrist:'hand_l',rightShoulder:'upperarm_r',rightElbow:'lowerarm_r',rightWrist:'hand_r',leftHip:'thigh_l',leftKnee:'calf_l',leftFoot:'foot_l',leftToe:'ball_l',rightHip:'thigh_r',rightKnee:'calf_r',rightFoot:'foot_r',rightToe:'ball_r'};
const clips:Record<string,{duration:number;frames:number[][];average:number[];source:string}>={};
const bind:Record<string,number[]>={};
for(const source of sources){
 const bytes=readFileSync(resolve(folder,source.file));
 if(createHash('sha256').update(bytes).digest('hex')!==source.sha256)throw new Error(`Source hash mismatch: ${source.file}`);
 const loader=new GLTFLoader();
 // Mesh textures are irrelevant to skeletal sampling and need no image decoder.
 loader.register(()=>({name:'motion-texture-stub',loadTexture:()=>Promise.resolve(new THREE.Texture())}));
 const gltf=await loader.parseAsync(bytes.buffer.slice(bytes.byteOffset,bytes.byteOffset+bytes.byteLength) as ArrayBuffer,'');
 const nodes=Object.values(joints).map(name=>{const node=gltf.scene.getObjectByName(name);if(!node)throw new Error(`Missing ${name}`);return node;});
 const root=gltf.scene.getObjectByName('root')!;
 const frame=()=>{
  gltf.scene.updateMatrixWorld(true);const origin=root.getWorldPosition(new THREE.Vector3());
  return nodes.flatMap(node=>{
   const p=node.getWorldPosition(new THREE.Vector3());
   // Source names use left-positive X; Bolts' named left limbs use negative X.
   return [-(p.x-origin.x),p.y-origin.y,p.z-origin.z].map(v=>Number(v.toFixed(5)));
  });
 };
 bind[source.file]=frame();
 for(const name of source.clips){
  const clip=gltf.animations.find(item=>item.name===name);if(!clip)throw new Error(`Missing clip ${name}`);
  const mixer=new THREE.AnimationMixer(gltf.scene),action=mixer.clipAction(clip);
  action.setLoop(THREE.LoopOnce,1);action.clampWhenFinished=true;action.play();
  const count=Math.ceil(clip.duration*30)+1,frames:number[][]=[];
  for(let i=0;i<count;i++){mixer.setTime(clip.duration*i/(count-1));frames.push(frame());}
  const average=frames[0].map((_,i)=>Number((frames.reduce((total,row)=>total+row[i],0)/count).toFixed(5)));
  clips[name]={duration:clip.duration,frames,average,source:source.file};
  mixer.stopAllAction();mixer.uncacheRoot(gltf.scene);
 }
}
const target=resolve('src/generated/mesh2motionData.ts');mkdirSync(resolve('src/generated'),{recursive:true});
writeFileSync(target,`// Generated by scripts/build-motion.ts from CC0 Mesh2Motion source clips.\n// Do not hand-edit; provenance: public/assets/animations/mesh2motion/provenance.json.\nexport const SOURCE_JOINTS=${JSON.stringify(Object.keys(joints))} as const;\nexport const SOURCE_BIND:Record<string,number[]>=${JSON.stringify(bind)};\nexport const SOURCE_CLIPS:Record<string,{duration:number;frames:number[][];average:number[];source:string}>=${JSON.stringify(clips)};\n`);
console.log(`Baked ${Object.keys(clips).length} clips, ${Object.values(clips).reduce((n,c)=>n+c.frames.length,0)} frames into ${target}`);
